import { runCodexAgent, runClaudeAgent } from './agent-cli';
import type { AgentRunResult, ArmId, JudgeOrderResult, JudgePairResult, JudgeScore, JudgeSide, PairVerdict, TaskDefinition } from './types';

const IDENTIFYING_PATTERNS: RegExp[] = [
  /^\s*[+-]?\s*Co-Authored-By:.*$/gim,
  /^\s*[+-]?\s*Generated with .*$/gim,
  /^\s*[+-]?\s*<!--.*?(claude|codex|gemini|gpt|anthropic|openai|copilot|llm|ai[- ]generated).*?-->.*$/gim,
  /^\s*[+-]?\s*(\/\/|#|\/\*|\*|--)\s*.*(generated by|written by|ai[- ]generated|claude|codex|gemini|gpt-|anthropic|openai)\b.*$/gim,
];

export function stripIdentifyingText(diff: string): string {
  let out = diff;
  for (const pattern of IDENTIFYING_PATTERNS) {
    out = out.replace(pattern, '');
  }
  return out
    .split('\n')
    .filter((line) => line.trim() !== '')
    .join('\n');
}

export function buildJudgePrompt(taskPrompt: string, diffX: string, diffY: string): string {
  return [
    'You are one of two independent judges comparing two patches for the same coding task. You do not know which system produced which patch, and the patches have been scrubbed of attribution. Judge only on merit.',
    '',
    'Task (the outcome requested):',
    taskPrompt,
    '',
    'Patch X:',
    '```diff',
    diffX,
    '```',
    '',
    'Patch Y:',
    '```diff',
    diffY,
    '```',
    '',
    'Score EACH patch 0-10 on: "correctBeyondTests" (would the change actually solve the task, beyond what tests check), "fitsCodebaseStyle" (matches the surrounding code), "noUnrequestedChanges" (10 = nothing beyond the task).',
    'Also answer "wouldMergeAsIs" per patch as true/false.',
    'Pick an overall winner ("x", "y", or "tie") — a tie is honest when the patches are comparable.',
    '',
    'Return ONLY JSON in this exact shape:',
    '{"x": {"correctBeyondTests": 0, "fitsCodebaseStyle": 0, "noUnrequestedChanges": 0, "wouldMergeAsIs": true, "notes": "..."},',
    ' "y": {"correctBeyondTests": 0, "fitsCodebaseStyle": 0, "noUnrequestedChanges": 0, "wouldMergeAsIs": true, "notes": "..."},',
    ' "winner": "x"}',
  ].join('\n');
}

export function parseJudgeResponse(text: string): { scores: Record<JudgeSide, JudgeScore>; winner: JudgeSide | 'tie' } | null {
  const jsonMatch = text.match(/\{[\s\S]*\}/);
  if (!jsonMatch) return null;
  let parsed: Record<string, unknown>;
  try {
    parsed = JSON.parse(jsonMatch[0]) as Record<string, unknown>;
  } catch {
    return null;
  }
  const side = (key: string): JudgeScore | null => {
    const raw = parsed[key];
    if (!raw || typeof raw !== 'object') return null;
    const obj = raw as Record<string, unknown>;
    const score = (field: string): number => {
      const value = Number(obj[field]);
      if (!Number.isFinite(value)) return NaN;
      return Math.max(0, Math.min(10, value));
    };
    const correctBeyondTests = score('correctBeyondTests');
    const fitsCodebaseStyle = score('fitsCodebaseStyle');
    const noUnrequestedChanges = score('noUnrequestedChanges');
    if ([correctBeyondTests, fitsCodebaseStyle, noUnrequestedChanges].some(Number.isNaN)) return null;
    return {
      correctBeyondTests,
      fitsCodebaseStyle,
      noUnrequestedChanges,
      wouldMergeAsIs: obj['wouldMergeAsIs'] === true,
      notes: typeof obj['notes'] === 'string' ? obj['notes'].slice(0, 500) : '',
    };
  };
  const x = side('x');
  const y = side('y');
  const winnerRaw = parsed['winner'];
  const winner: JudgeSide | 'tie' = winnerRaw === 'x' || winnerRaw === 'y' ? winnerRaw : 'tie';
  if (!x || !y) return null;
  return { scores: { x, y }, winner };
}

export type JudgeRunner = (prompt: string) => Promise<AgentRunResult>;

export async function judgeOneOrder(
  runJudge: JudgeRunner,
  task: TaskDefinition,
  subjectDiff: string,
  baselineDiff: string,
  subjectSide: JudgeSide,
): Promise<JudgeOrderResult> {
  const xDiff = subjectSide === 'x' ? subjectDiff : baselineDiff;
  const yDiff = subjectSide === 'x' ? baselineDiff : subjectDiff;
  const prompt = buildJudgePrompt(task.prompt, xDiff, yDiff);
  const result = await runJudge(prompt);
  const parsed = parseJudgeResponse(result.finalText);
  if (!parsed) {
    throw new Error(`judge returned no parseable verdict: ${(result.error ?? result.finalText).slice(0, 300)}`);
  }
  return {
    subjectSide,
    scores: parsed.scores,
    winner: parsed.winner,
    rawText: result.finalText,
  };
}

function subjectWonOrder(order: JudgeOrderResult): boolean {
  return order.winner !== 'tie' && order.winner === order.subjectSide;
}

function baselineWonOrder(order: JudgeOrderResult): boolean {
  return order.winner !== 'tie' && order.winner !== order.subjectSide;
}

export interface JudgedRunNumbers {
  /** The arm-side run whose patch is in this pair. */
  subjectRunNumber: number;
  /** The arm-A run whose patch is the baseline side. */
  baselineRunNumber: number;
}

/**
 * Both orders must favour the subject for a win; anything else is a tie.
 * A judge that cannot answer is recorded as judge-unavailable and NEVER
 * silently swapped for a different model (the sibling benchmark's fallback
 * turned "two judges" into one judge twice).
 */
export async function judgePair(
  judge: 'claude' | 'codex',
  runJudge: JudgeRunner,
  task: TaskDefinition,
  armId: ArmId,
  subjectDiff: string,
  baselineDiff: string,
  judgedRuns?: JudgedRunNumbers,
): Promise<JudgePairResult> {
  const identity = judgedRuns
    ? { subjectRunNumber: judgedRuns.subjectRunNumber, baselineRunNumber: judgedRuns.baselineRunNumber }
    : {};
  const orders: JudgeOrderResult[] = [];
  try {
    orders.push(await judgeOneOrder(runJudge, task, subjectDiff, baselineDiff, 'x'));
    orders.push(await judgeOneOrder(runJudge, task, subjectDiff, baselineDiff, 'y'));
  } catch (error) {
    return {
      taskId: task.id,
      armId,
      judge,
      orders,
      verdict: 'judge-unavailable',
      error: error instanceof Error ? error.message : String(error),
      ...identity,
    };
  }
  let verdict: PairVerdict = 'tie';
  if (orders.every(subjectWonOrder)) verdict = 'arm-win';
  else if (orders.every(baselineWonOrder)) verdict = 'baseline-win';
  return { taskId: task.id, armId, judge, orders, verdict, ...identity };
}

export function claudeJudgeRunner(model: string, logPathFor: (order: string) => string, timeoutMs = 600_000): JudgeRunner {
  let counter = 0;
  return async (prompt: string) => {
    counter += 1;
    return runClaudeAgent({
      prompt,
      cwd: process.cwd(),
      logPath: logPathFor(`claude-${counter}`),
      timeoutMs,
      model,
      readOnly: true,
    });
  };
}

export function codexJudgeRunner(logPathFor: (order: string) => string, timeoutMs = 600_000): JudgeRunner {
  let counter = 0;
  return async (prompt: string) => {
    counter += 1;
    return runCodexAgent({
      prompt,
      cwd: process.cwd(),
      logPath: logPathFor(`codex-${counter}`),
      timeoutMs,
    });
  };
}
