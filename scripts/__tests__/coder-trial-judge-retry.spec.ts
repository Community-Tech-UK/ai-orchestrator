import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, expect, it } from 'vitest';

const directories: string[] = [];
afterEach(() => { for (const dir of directories.splice(0)) rmSync(dir, { recursive: true, force: true }); });
const score = () => ({ correctBeyondTests: 8, fitsCodebaseStyle: 9, noUnrequestedChanges: 10, wouldMergeAsIs: true });
const order = (subjectSide: string) => ({ subjectSide, winner: subjectSide, scores: { x: score(), y: score() } });
function fixture() {
  const dir = mkdtempSync(join(tmpdir(), 'coder-judge-retry-')); directories.push(dir);
  mkdirSync(join(dir, 'judge')); mkdirSync(join(dir, 'patches'));
  const bank = join(dir, 'bank.json');
  writeFileSync(bank, JSON.stringify({ tasks: [{ id: 'T1', prompt: 'Fix the counter.' }] }));
  const records = ['S1', 'A', 'H'].flatMap(armId => [2, 1].map(runNumber => ({
    taskId: 'T1', armId, runNumber, patchPath: join(dir, 'patches', `T1-${armId}-run${runNumber}.patch`),
    score: { hiddenTests: { passed: armId !== 'H' }, damageOk: true },
  })));
  for (const r of records) writeFileSync(r.patchPath, `+${r.armId === 'A' ? 'baseline' : 'subject'}-${r.runNumber}\n+// Generated by Claude\n`);
  const runs = join(dir, 'runs.jsonl');
  const saveRuns = () => writeFileSync(runs, records.map(r => JSON.stringify(r)).join('\n')); saveRuns();
  const identity = { taskId: 'T1', armId: 'S1', subjectRunNumber: 2, baselineRunNumber: 2 };
  const pairs = [
    { ...identity, judge: 'claude', verdict: 'arm-win', orders: [order('x'), order('y')] },
    { ...identity, judge: 'codex', verdict: 'judge-unavailable', orders: [] as ReturnType<typeof order>[] },
  ];
  const pairPath = join(dir, 'judge/T1-S1.json');
  const savePairs = () => writeFileSync(pairPath, JSON.stringify(pairs)); savePairs();
  const invoke = (...args: string[]) => spawnSync(process.execPath, [
    'scripts/coder-trial-judge-retry.mjs', '--session', dir, '--bank', bank, ...args,
  ], { encoding: 'utf8' });
  const prepare = () => { const r = invoke(); expect(r.status, r.stderr).toBe(0); return JSON.parse(r.stdout); };
  const respond = (jobs: { id: string; promptSha256: string }[]) => jobs.map(job => ({
    id: job.id, promptSha256: job.promptSha256, result: { winner: 'tie', x: score(), y: score() },
  }));
  const apply = (responses: unknown) => {
    const path = join(dir, 'responses.json'); writeFileSync(path, JSON.stringify(responses));
    return invoke('--responses', path);
  };
  return { dir, bank, records, runs, saveRuns, pairs, pairPath, savePairs, invoke, prepare, respond, apply };
}

it('prepares only missing judges in both blind orders using the first saved repeat, preserving inputs', () => {
  const f = fixture(), before = readFileSync(f.pairPath), runs = readFileSync(f.runs), r = f.prepare();
  expect(r.jobs).toHaveLength(2);
  expect(r.jobs.map((j: { judge: string; subjectSide: string }) => [j.judge, j.subjectSide])).toEqual([['codex', 'x'], ['codex', 'y']]);
  expect(r.jobs[0]).toMatchObject({ subjectRunNumber: 2, baselineRunNumber: 2 });
  expect(r.jobs[0].prompt).toContain('Patch X:\n```diff\n+subject-2');
  expect(r.jobs[1].prompt).toContain('Patch X:\n```diff\n+baseline-2');
  expect(r.jobs[0].prompt).not.toMatch(/Claude|S1/);
  expect(r.pairs[0].judges[0]).toEqual(f.pairs[0]);
  expect(r.inputHashes['judge/T1-S1.json']).toBe(createHash('sha256').update(before).digest('hex'));
  expect(readFileSync(f.pairPath)).toEqual(before); expect(readFileSync(f.runs)).toEqual(runs);
});

it('keeps a successful first order and merges only the missing order into a separate result', () => {
  const f = fixture(); f.pairs[1].orders.push(order('x')); f.savePairs();
  const prepared = f.prepare(); expect(prepared.jobs).toHaveLength(1); expect(prepared.jobs[0].subjectSide).toBe('y');
  const result = f.apply(f.respond(prepared.jobs)); expect(result.status, result.stderr).toBe(0);
  const merged = JSON.parse(result.stdout);
  expect(merged.jobs).toEqual([]);
  expect(merged.pairs[0].judges[0]).toEqual(f.pairs[0]);
  expect(merged.pairs[0].judges[1]).toMatchObject({ verdict: 'tie', orders: [order('x'), { subjectSide: 'y', winner: 'tie' }] });
  expect(JSON.parse(readFileSync(f.pairPath, 'utf8'))[1].verdict).toBe('judge-unavailable');
});

it('rejects stale, duplicate, unrequested and malformed response evidence without clamping rubric scores', () => {
  const f = fixture(), prepared = f.prepare();
  const good = f.respond(prepared.jobs);
  const badCases = [
    [{ ...good[0], promptSha256: 'stale' }], [good[0], good[0]], [{ ...good[0], id: 'unknown' }],
    [{ ...good[0], result: { ...good[0].result, x: { ...score(), correctBeyondTests: 11 } } }],
    [{ ...good[0], result: { ...good[0].result, winner: 'invalid' } }],
    [{ ...good[0], result: { ...good[0].result, y: { ...score(), wouldMergeAsIs: 'true' } } }],
  ];
  for (const responses of badCases) expect(f.apply(responses).status).toBe(2);
  const result = f.apply([good[0]]); expect(result.status, result.stderr).toBe(0);
  expect(JSON.parse(result.stdout).jobs).toHaveLength(1);
});

it('rejects wrong saved identities, duplicate cells and patch paths outside the session', () => {
  const f = fixture(); f.pairs[1].subjectRunNumber = 1; f.savePairs();
  expect(f.invoke().status).toBe(2);
  f.pairs[1].subjectRunNumber = 2; f.savePairs();
  f.records.push(f.records[0]); f.saveRuns(); expect(f.invoke().status).toBe(2);
  f.records.pop(); f.records[0].patchPath = f.bank; f.saveRuns(); expect(f.invoke().status).toBe(2);
});

it('does not retry complete pairs or judge unsuccessful tasks', () => {
  const f = fixture(); f.pairs[1] = { ...f.pairs[1], verdict: 'arm-win', orders: [order('x'), order('y')] }; f.savePairs();
  expect(f.prepare().jobs).toEqual([]);
  f.records[0].score.damageOk = false; f.saveRuns(); expect(f.prepare().pairs).toEqual([]);
});
