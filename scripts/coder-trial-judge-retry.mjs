#!/usr/bin/env node
/** Offline judge retry preparation/import. Never calls providers or overwrites saved evidence. */
import { createHash } from 'node:crypto';
import { readFileSync, realpathSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const hash = text => createHash('sha256').update(text).digest('hex');
const arms = ['H', 'HM', 'S1', 'S2', 'S3', 'S4'];
const solved = r => r?.score?.hiddenTests?.passed === true && r?.score?.damageOk === true;
const validScore = score => score && typeof score.wouldMergeAsIs === 'boolean'
  && ['correctBeyondTests', 'fitsCodebaseStyle', 'noUnrequestedChanges'].every(key =>
    typeof score[key] === 'number' && Number.isFinite(score[key]) && score[key] >= 0 && score[key] <= 10);
const validOrder = order => order && ['x', 'y'].includes(order.subjectSide)
  && ['x', 'y', 'tie'].includes(order.winner) && ['x', 'y'].every(side => validScore(order.scores?.[side]));
const verdict = orders => orders.length !== 2 ? 'judge-unavailable'
  : orders.every(o => o.winner === o.subjectSide) ? 'arm-win'
    : orders.every(o => o.winner !== 'tie' && o.winner !== o.subjectSide) ? 'baseline-win' : 'tie';

// Frozen prompt/attribution rules from the trial's judge.ts. Keep both presentations identical to that trial.
function scrub(diff) {
  const patterns = [
    /^\s*[+-]?\s*Co-Authored-By:.*$/gim,
    /^\s*[+-]?\s*Generated with .*$/gim,
    /^\s*[+-]?\s*<!--.*?(claude|codex|gemini|gpt|anthropic|openai|copilot|llm|ai[- ]generated).*?-->.*$/gim,
    /^\s*[+-]?\s*(\/\/|#|\/\*|\*|--)\s*.*(generated by|written by|ai[- ]generated|claude|codex|gemini|gpt-|anthropic|openai)\b.*$/gim,
  ];
  for (const pattern of patterns) diff = diff.replace(pattern, '');
  return diff.split('\n').filter(line => line.trim() !== '').join('\n');
}
function prompt(task, x, y) {
  return [
    'You are one of two independent judges comparing two patches for the same coding task. You do not know which system produced which patch, and the patches have been scrubbed of attribution. Judge only on merit.',
    '', 'Task (the outcome requested):', task, '', 'Patch X:', '```diff', x, '```',
    '', 'Patch Y:', '```diff', y, '```', '',
    'Score EACH patch 0-10 on: "correctBeyondTests" (would the change actually solve the task, beyond what tests check), "fitsCodebaseStyle" (matches the surrounding code), "noUnrequestedChanges" (10 = nothing beyond the task).',
    'Also answer "wouldMergeAsIs" per patch as true/false.',
    'Pick an overall winner ("x", "y", or "tie") — a tie is honest when the patches are comparable.', '',
    'Return ONLY JSON in this exact shape:',
    '{"x": {"correctBeyondTests": 0, "fitsCodebaseStyle": 0, "noUnrequestedChanges": 0, "wouldMergeAsIs": true, "notes": "..."},',
    ' "y": {"correctBeyondTests": 0, "fitsCodebaseStyle": 0, "noUnrequestedChanges": 0, "wouldMergeAsIs": true, "notes": "..."},',
    ' "winner": "x"}',
  ].join('\n');
}

function prepare(session, bank) {
  const inputHashes = {};
  const read = (key, path = join(session, key)) => {
    const text = readFileSync(path, 'utf8'); inputHashes[key] = hash(text); return text;
  };
  const tasks = JSON.parse(read('bank.json', bank)).tasks;
  if (!Array.isArray(tasks) || !tasks.length || new Set(tasks.map(t => t.id)).size !== tasks.length
    || tasks.some(t => typeof t.id !== 'string' || !/^[A-Za-z0-9]+(?:-[A-Za-z0-9]+)*$/.test(t.id) || typeof t.prompt !== 'string')) throw new Error('Invalid task bank');
  const records = read('runs.jsonl').split('\n').filter(l => l.trim()).map(l => JSON.parse(l));
  const cells = new Set();
  for (const r of records) {
    const key = `${r.taskId}|${r.armId}|${r.runNumber}`;
    if (!tasks.some(t => t.id === r.taskId) || !['A', ...arms].includes(r.armId)
      || ![1, 2, 3].includes(r.runNumber) || cells.has(key)) throw new Error('Duplicate or unexpected saved cell');
    cells.add(key);
  }
  const patch = r => {
    const relative = `patches/${r.taskId}-${r.armId}-run${r.runNumber}.patch`;
    const path = join(session, relative);
    // Both lexical and resolved paths must be the session's expected artifact, never another source tree.
    if (r.patchPath !== path || realpathSync(path) !== join(realpathSync(session), relative)) throw new Error('Patch identity/path mismatch');
    return scrub(read(relative));
  };
  const pairs = [], jobs = [];
  for (const task of tasks) for (const armId of arms) {
    // Match the historical runner: first saved repeat, not best or lowest-numbered repeat.
    const subject = records.find(r => r.taskId === task.id && r.armId === armId);
    const baseline = records.find(r => r.taskId === task.id && r.armId === 'A');
    if (!solved(subject) || !solved(baseline)) continue;
    const identity = { taskId: task.id, armId, subjectRunNumber: subject.runNumber, baselineRunNumber: baseline.runNumber };
    const path = `judge/${task.id}-${armId}.json`;
    const saved = existsSync(join(session, path)) ? JSON.parse(read(path)) : [];
    if (!Array.isArray(saved) || saved.some(p => !['claude', 'codex'].includes(p.judge))
      || new Set(saved.map(p => p.judge)).size !== saved.length) throw new Error('Invalid saved judge pairs');
    const subjectDiff = patch(subject), baselineDiff = patch(baseline);
    const judges = ['claude', 'codex'].map(judge => {
      const old = saved.find(p => p.judge === judge) ?? { ...identity, judge, verdict: 'judge-unavailable', orders: [] };
      if (Object.entries(identity).some(([key, value]) => old[key] !== value)
        || !['arm-win', 'baseline-win', 'tie', 'judge-unavailable'].includes(old.verdict)
        || !Array.isArray(old.orders) || old.orders.some(o => !validOrder(o))
        || new Set(old.orders.map(o => o.subjectSide)).size !== old.orders.length) throw new Error('Invalid saved judge identity/orders');
      if ((old.verdict === 'judge-unavailable' && old.orders.length === 2)
        || (old.verdict !== 'judge-unavailable' && (old.orders.length !== 2 || old.verdict !== verdict(old.orders)))) throw new Error('Inconsistent saved judge verdict');
      for (const subjectSide of ['x', 'y']) {
        if (old.orders.some(o => o.subjectSide === subjectSide)) continue;
        const text = prompt(task.prompt, subjectSide === 'x' ? subjectDiff : baselineDiff, subjectSide === 'x' ? baselineDiff : subjectDiff);
        jobs.push({ ...identity, judge, subjectSide, id: `${task.id}|${armId}|${subject.runNumber}|${baseline.runNumber}|${judge}|${subjectSide}`,
          promptSha256: hash(text), prompt: text });
      }
      return old;
    });
    pairs.push({ ...identity, judges });
  }
  return { inputHashes, pairs, jobs };
}

function apply(prepared, responses) {
  if (!Array.isArray(responses)) throw new Error('Invalid response evidence');
  const seen = new Set();
  for (const response of responses) {
    const job = prepared.jobs.find(j => j.id === response.id);
    const result = response.result;
    if (!job || seen.has(response.id) || response.promptSha256 !== job.promptSha256) throw new Error('Unexpected, duplicate or stale response');
    if (!result || !['x', 'y', 'tie'].includes(result.winner) || !validScore(result.x) || !validScore(result.y)) throw new Error('Invalid response rubric');
    seen.add(response.id);
    const pair = prepared.pairs.find(p => p.taskId === job.taskId && p.armId === job.armId).judges.find(p => p.judge === job.judge);
    pair.orders.push({ subjectSide: job.subjectSide, winner: result.winner, scores: { x: result.x, y: result.y } });
    pair.orders.sort((a, b) => a.subjectSide.localeCompare(b.subjectSide));
    pair.verdict = verdict(pair.orders);
    if (pair.verdict !== 'judge-unavailable') delete pair.error;
  }
  prepared.jobs = prepared.jobs.filter(j => !seen.has(j.id));
  return prepared;
}

try {
  const args = process.argv.slice(2);
  if (![4, 6].includes(args.length) || args[0] !== '--session' || args[2] !== '--bank'
    || (args.length === 6 && args[4] !== '--responses')) throw new Error('Usage: --session DIR --bank FILE [--responses FILE]');
  const result = prepare(args[1], args[3]);
  if (args.length === 6) {
    const raw = readFileSync(args[5], 'utf8');
    apply(result, JSON.parse(raw)); result.responsesSha256 = hash(raw);
  }
  console.log(JSON.stringify(result, null, 2));
} catch (error) {
  // File/JSON diagnostics can contain source data; emit only our explicit validation messages.
  console.error(error.code || error instanceof SyntaxError ? 'Could not read saved judge evidence' : error.message);
  process.exitCode = 2;
}
